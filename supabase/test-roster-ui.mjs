import fs from 'node:fs/promises';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const source = await fs.readFile(new URL('../app.js',import.meta.url),'utf8');
const context = vm.createContext({location:{hash:''},document:{querySelector(){return {value:''}}}});
vm.runInContext(source.slice(0,source.indexOf("$('#task-status').innerHTML")),context);
const run = code => vm.runInContext(code,context);
run(`
  phase='ready'; rosterReady=true; session={user:{id:'lead'}};
  state.teams=[{id:'root',parent_team_id:null},{id:'leaf',parent_team_id:'root'},{id:'other',parent_team_id:null}];
  state.projects=[{id:'p',status:'active'},{id:'other-p',status:'active'}];
  state.profiles=[{id:'lead',display_name:'Lead'},{id:'a',display_name:'Alias A'},{id:'b',display_name:'Alias B'}];
  state.leadership=[{user_id:'lead',role:'project_lead',team_id:'root',project_id:'p',revoked_at:null}];
  state.rosterPeople=[{id:'person',display_name:'One person'},{id:'future',display_name:'Future person'}];
  state.rosterGroups=[{person_id:'person',team_id:'root'},{person_id:'future',team_id:'leaf'}];
  state.rosterAccounts=[{person_id:'person',user_id:'a'},{person_id:'person',user_id:'b'}];
  state.memberships=[{team_id:'root',user_id:'a'},{team_id:'root',user_id:'b'}];
`);
assert.equal(run("assignmentPeople('leaf','p').filter(p=>p.name==='One person').length"),1);
assert.equal(run("assignmentPeople('leaf','p').find(p=>p.name==='Future person').pending"),true);
assert.equal(run("assignmentPeople('root','p').some(p=>p.name==='Future person')"),false);
assert.equal(run("taskAssignedTo({assignee_person_id:'person'},'a')"),true);
assert.equal(run("taskAssignedTo({assignee_person_id:'person'},'b')"),true);
assert.equal(run("taskAssignedTo({assignee_person_id:'person'},'lead')"),false);
assert.equal(run("taskAssigneeName({assignee_id:'lead'})"),'Lead');
assert.equal(run("taskAssigneeName({assignee_person_id:'future'})"),'Future person');
assert.equal(run("taskAssigneeName({})"),'Unassigned group work');
assert.equal(run("canManageIn('leaf','p')"),true);
assert.equal(run("canManageIn('other','p')"),false);
assert.equal(run("canManageIn('leaf','other-p')"),false);
assert.equal(run("JSON.stringify(assigneeValues('person:future'))"),JSON.stringify({assignee_id:null,assignee_person_id:'future'}));
assert.equal(run("JSON.stringify(assigneeValues('lead'))"),JSON.stringify({assignee_id:'lead',assignee_person_id:null}));
assert.equal(run("JSON.stringify(assigneeValues(''))"),JSON.stringify({assignee_id:null,assignee_person_id:null}));
run("preview.mode='member'; preview.subject='a'");
assert.equal(run('canCreateSubteam()'),false);
console.log('UI model checks passed: deduplication, pending labels, alias ownership, scope, assignment switching, and read-only preview.');
